/**
 * Builds the guess lexicon from Webster's Second International (1934).
 *
 * The 1934 copyright lapsed, the file ships with every Unix, and it is the only
 * English word list on this machine that comes with a provenance anyone can
 * check. It is a dictionary, not a corpus, so it says nothing about how common a
 * word is — which is why the *answer* pool is curated by hand in `answers.ts`
 * and this list is only what a solver is allowed to type.
 *
 * One module per word length, deliberately. A case of six letters has no use for
 * the seven-letter list, and shipping all of them in the entry chunk put 850 KB
 * of dictionary in front of a first paint. `lexicon/index.ts` loads them on
 * demand and caches them.
 *
 * Run: node scripts/build-lexicon.mjs
 */

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const SOURCE = '/usr/share/dict/web2'
const OUT = join(here, '..', 'src', 'engine', 'lexicon')

const MIN = 3
const MAX = 12

const raw = readFileSync(SOURCE, 'utf8')
const byLength = new Map()

for (const line of raw.split('\n')) {
  const word = line.trim()
  if (word.length < MIN || word.length > MAX) continue
  if (!/^[a-z]+$/.test(word)) continue
  // A word with no vowel and no y is not something anyone types on purpose.
  if (!/[aeiouy]/.test(word)) continue
  if (!byLength.has(word.length)) byLength.set(word.length, new Set())
  byLength.get(word.length).add(word)
}

const lengths = [...byLength.keys()].sort((a, b) => a - b)
mkdirSync(OUT, { recursive: true })

let total = 0
let bytes = 0

for (const length of lengths) {
  const words = [...byLength.get(length)].sort()
  total += words.length

  // Front-coded: each word keeps only the length of the prefix it shares with the
  // one before it, then its own tail. Sorted English shares a lot of prefixes, so
  // a nine-letter list loses about a third of its bytes before gzip even starts.
  const coded = []
  let previous = ''
  for (const word of words) {
    let shared = 0
    while (shared < previous.length && shared < word.length && previous[shared] === word[shared]) shared += 1
    // The prefix is one character, so it cannot be longer than nine.
    const prefix = Math.min(shared, 8)
    coded.push(`${prefix}${word.slice(prefix)}`)
    previous = word
  }

  const body = `/**
 * The ${length}-letter guess list, front-coded and generated by
 * \`scripts/build-lexicon.mjs\` from Webster's Second International (1934). Do not
 * edit by hand — run the script. Decoded by \`lexicon/index.ts\`.
 *
 * ${words.length} words.
 */

export const CODED = '${coded.join('\\n')}'
`
  writeFileSync(join(OUT, `${length}.ts`), body)
  bytes += Buffer.byteLength(body)
}

const index = `/**
 * The guess lexicon, one module per word length.
 *
 * These are words a solver may *type*. What a solver may be *given* as an answer
 * is a much smaller, hand-curated list in \`answers.ts\`, because a dictionary
 * with every English word in it is a fine keyboard and a terrible puzzle.
 *
 * One module per length, decoded on demand and cached, so a six-letter puzzle
 * never pays for the nine-letter list. Each module is front-coded — a shared
 * prefix length and a tail — which is worth about a third of the bytes on sorted
 * English. Generated by \`scripts/build-lexicon.mjs\`.
 */

export const GUESS_LENGTHS: readonly number[] = [${lengths.join(', ')}] as const

type Loader = () => Promise<{ readonly CODED: string }>

const LOADERS: Readonly<Record<number, Loader>> = {
${lengths.map((length) => `  ${length}: () => import('./${length}'),`).join('\n')}
}

/** Turn "0abacay\\n1bacus" back into the words it stands for. */
export function decode(coded: string): readonly string[] {
  const out: string[] = []
  let previous = ''
  for (const line of coded.split('\\n')) {
    if (line.length === 0) continue
    const shared = Number(line[0])
    const next = previous.slice(0, shared) + line.slice(1)
    out.push(next)
    previous = next
  }
  return out
}

const cache = new Map<number, readonly string[]>()

export async function guessesOfLength(length: number): Promise<readonly string[]> {
  const cached = cache.get(length)
  if (cached) return cached
  const loader = LOADERS[length]
  if (!loader) return []
  const module = await loader()
  const list = decode(module.CODED)
  cache.set(length, list)
  return list
}
`

writeFileSync(join(OUT, 'index.ts'), index)
bytes += Buffer.byteLength(index)

console.log(`wrote ${lengths.length} length modules and an index to ${OUT}`)
for (const length of lengths) console.log(`  ${length} letters: ${byLength.get(length).size}`)
console.log(`  total ${total} words, ${(bytes / 1024).toFixed(0)} KB across ${lengths.length + 1} modules`)
